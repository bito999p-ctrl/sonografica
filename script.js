/* ── Artist Ambient Background Theming (Focal Zone Observer) ── */
function setupArtistAmbientObserver() {
    const THEMED_ARTISTS = [
        'valotoa',
        'hizumi',
        'pophoper',
        'stray',
        'dayendnight',
        'rupture'
    ];

    const artistEls = THEMED_ARTISTS
        .map(id => ({ id, el: document.getElementById(id) }))
        .filter(item => item.el);

    if (!artistEls.length) return;

    let ticking = false;
    let currentThemeClass = '';

    function checkActiveArtist() {
        const vHeight = window.innerHeight;
        const focalTop = vHeight * 0.35;
        const focalBottom = vHeight * 0.65;

        let activeArtistId = null;

        for (const item of artistEls) {
            const rect = item.el.getBoundingClientRect();
            if (rect.top <= focalBottom && rect.bottom >= focalTop) {
                activeArtistId = item.id;
                break;
            }
        }

        const newThemeClass = activeArtistId ? `theme-${activeArtistId}` : '';

        if (newThemeClass !== currentThemeClass) {
            if (currentThemeClass) {
                document.body.classList.remove(currentThemeClass);
            }
            if (newThemeClass) {
                document.body.classList.add(newThemeClass);
            }
            currentThemeClass = newThemeClass;
        }
    }

    function onScroll() {
        if (!ticking) {
            requestAnimationFrame(() => {
                checkActiveArtist();
                ticking = false;
            });
            ticking = true;
        }
    }

    window.addEventListener('scroll', onScroll, { passive: true });
    window.addEventListener('resize', checkActiveArtist, { passive: true });
    checkActiveArtist();
}

function setupPlayerHeightSync() {
    syncPlayerHeights();
    if ('ResizeObserver' in window) {
        const ro = new ResizeObserver(() => {
            syncPlayerHeights();
        });
        document.querySelectorAll('.youtube-card').forEach(yt => ro.observe(yt));
    }
    window.addEventListener('resize', syncPlayerHeights, { passive: true });
    setTimeout(syncPlayerHeights, 300);
}

function syncPlayerHeights() {
    if (window.innerWidth <= 960) {
        document.querySelectorAll('.suno-native-player').forEach(p => p.style.height = '');
        return;
    }
    document.querySelectorAll('.media-grid').forEach(grid => {
        const ytCard = grid.querySelector('.youtube-card');
        const sunoPlayer = grid.querySelector('.suno-native-player');
        const sunoToggle = grid.querySelector('.suno-accordion-toggle');
        const sunoHeader = grid.querySelector('.suno-jukebox .media-card-header');
        if (ytCard && sunoPlayer && sunoToggle && sunoHeader) {
            const ytHeight = ytCard.getBoundingClientRect().height;
            const toggleHeight = sunoToggle.offsetHeight || 44;
            const headerHeight = sunoHeader.offsetHeight || 38;
            const targetHeight = ytHeight - toggleHeight - headerHeight;
            if (targetHeight > 180) {
                sunoPlayer.style.height = `${Math.round(targetHeight)}px`;
            }
        }
    });
}

/* ── Virtual Analog Hardware Audio Player Deck Engine ── */
function setupAudioDeck() {
    const deck = document.getElementById('sonografica-deck');
    if (!deck) return;

    const playlist = (typeof SONOGRAFICA_PLAYLIST !== 'undefined' && Array.isArray(SONOGRAFICA_PLAYLIST)) 
        ? SONOGRAFICA_PLAYLIST 
        : [];
    if (!playlist.length) return;

    const audio = new Audio();
    audio.preload = 'metadata';

    const coverImg = document.getElementById('deck-cover-img');
    const trackNumEl = document.getElementById('deck-track-num');
    const titleEl = document.getElementById('deck-track-title');
    const artistEl = document.getElementById('deck-artist-name');
    const statusLabel = document.getElementById('deck-status-label');
    const shuffleBadge = document.getElementById('deck-shuffle-badge');
    const btnPlay = document.getElementById('deck-btn-play');
    const iconPlay = btnPlay ? btnPlay.querySelector('.icon-play') : null;
    const iconPause = btnPlay ? btnPlay.querySelector('.icon-pause') : null;
    const playLabel = document.getElementById('deck-play-label');
    const btnStop = document.getElementById('deck-btn-stop');
    const btnPrev = document.getElementById('deck-btn-prev');
    const btnNext = document.getElementById('deck-btn-next');
    const btnShuffle = document.getElementById('deck-shuffle-toggle');
    const currentTimeEl = document.getElementById('deck-current-time');
    const durationEl = document.getElementById('deck-duration');
    const progressWrap = document.getElementById('deck-progress-wrap');
    const progressFill = document.getElementById('deck-progress-fill');
    const volumeSlider = document.getElementById('deck-volume-slider');
    const drawerToggle = document.getElementById('deck-playlist-toggle');
    const drawerClose = document.getElementById('deck-tracklist-close');
    const drawer = document.getElementById('deck-tracklist-drawer');
    const tracklistItems = document.getElementById('deck-tracklist-items');

    let currentIndex = 0;
    let isPlaying = false;
    let isShuffle = true; // Default to Random / Shuffle mode
    let shuffleQueue = [];
    let queuePointer = 0;

    function buildShuffleQueue(firstIndex) {
        const indices = playlist.map((_, i) => i);
        for (let i = indices.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [indices[i], indices[j]] = [indices[j], indices[i]];
        }
        if (typeof firstIndex === 'number') {
            const at = indices.indexOf(firstIndex);
            if (at > -1) {
                indices.splice(at, 1);
                indices.unshift(firstIndex);
            }
        }
        shuffleQueue = indices;
        queuePointer = 0;
    }

    // Populate tracklist drawer
    if (tracklistItems) {
        tracklistItems.innerHTML = '';
        playlist.forEach((track, idx) => {
            const row = document.createElement('div');
            row.className = `deck-track-row ${idx === 0 ? 'is-active' : ''}`;
            row.dataset.index = idx;
            row.innerHTML = `
                <div class="track-row-left">
                    <span class="track-row-num">${track.num}</span>
                    <span class="track-row-title">${escapeHtml(track.title)}</span>
                </div>
                <span class="track-row-artist">${escapeHtml(track.artist)}</span>
            `;
            row.addEventListener('click', () => {
                if (isShuffle) buildShuffleQueue(idx);
                loadTrack(idx, true);
            });
            tracklistItems.appendChild(row);
        });
    }

    function formatTime(sec) {
        if (!sec || isNaN(sec) || !isFinite(sec)) return '00:00';
        const m = Math.floor(sec / 60);
        const s = Math.floor(sec % 60);
        return `${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
    }

    function updateTracklistHighlight() {
        if (!tracklistItems) return;
        const rows = tracklistItems.querySelectorAll('.deck-track-row');
        rows.forEach((r, idx) => {
            r.classList.toggle('is-active', idx === currentIndex);
        });
    }

    function loadTrack(index, autoPlay = false) {
        if (index < 0 || index >= playlist.length) return;
        currentIndex = index;
        const track = playlist[currentIndex];

        audio.src = track.src;
        if (coverImg) coverImg.src = track.cover || 'sonografica_art.jpg';
        if (trackNumEl) trackNumEl.textContent = `TRK ${track.num} / ${String(playlist.length).padStart(2, '0')}`;
        if (titleEl) titleEl.textContent = track.title;
        if (artistEl) artistEl.textContent = track.artist;
        if (currentTimeEl) currentTimeEl.textContent = '00:00';
        if (progressFill) progressFill.style.width = '0%';

        updateTracklistHighlight();

        if (autoPlay) {
            playAudio();
        } else {
            setDeckState('stopped');
        }
    }

    function setDeckState(state) {
        deck.classList.remove('is-playing', 'is-paused');
        if (state === 'playing') {
            isPlaying = true;
            deck.classList.add('is-playing');
            if (statusLabel) statusLabel.textContent = 'PLAYING';
            if (iconPlay) iconPlay.style.display = 'none';
            if (iconPause) iconPause.style.display = 'block';
        } else if (state === 'paused') {
            isPlaying = false;
            deck.classList.add('is-paused');
            if (statusLabel) statusLabel.textContent = 'PAUSED';
            if (iconPlay) iconPlay.style.display = 'block';
            if (iconPause) iconPause.style.display = 'none';
        } else {
            isPlaying = false;
            if (statusLabel) statusLabel.textContent = 'STOPPED';
            if (iconPlay) iconPlay.style.display = 'block';
            if (iconPause) iconPause.style.display = 'none';
            if (progressFill) progressFill.style.width = '0%';
            if (currentTimeEl) currentTimeEl.textContent = '00:00';
        }
    }

    function playAudio() {
        audio.play().then(() => {
            setDeckState('playing');
        }).catch(err => {
            console.warn('Playback error / User interaction needed:', err);
            setDeckState('stopped');
        });
    }

    function pauseAudio() {
        audio.pause();
        setDeckState('paused');
    }

    function stopAudio() {
        audio.pause();
        audio.currentTime = 0;
        setDeckState('stopped');
    }

    function prevTrack() {
        if (isShuffle) {
            queuePointer = Math.max(0, queuePointer - 1);
            loadTrack(shuffleQueue[queuePointer], isPlaying);
        } else {
            const nextIdx = (currentIndex - 1 + playlist.length) % playlist.length;
            loadTrack(nextIdx, isPlaying);
        }
    }

    function nextTrack() {
        if (isShuffle) {
            queuePointer++;
            if (queuePointer >= shuffleQueue.length) {
                buildShuffleQueue();
            }
            loadTrack(shuffleQueue[queuePointer], isPlaying);
        } else {
            const nextIdx = (currentIndex + 1) % playlist.length;
            loadTrack(nextIdx, isPlaying);
        }
    }

    // Button Events
    if (btnPlay) {
        btnPlay.addEventListener('click', () => {
            if (isPlaying) {
                pauseAudio();
            } else {
                playAudio();
            }
        });
    }

    if (btnStop) {
        btnStop.addEventListener('click', stopAudio);
    }

    if (btnPrev) {
        btnPrev.addEventListener('click', prevTrack);
    }

    if (btnNext) {
        btnNext.addEventListener('click', nextTrack);
    }

    // Shuffle Mode Toggle
    if (btnShuffle) {
        btnShuffle.addEventListener('click', () => {
            isShuffle = !isShuffle;
            btnShuffle.classList.toggle('is-active', isShuffle);
            if (shuffleBadge) {
                shuffleBadge.innerHTML = isShuffle ? '&#8646; SHUFFLE' : '&#8644; ORDER';
                shuffleBadge.style.color = isShuffle ? 'var(--accent-rose)' : 'var(--accent-gold)';
            }
            if (isShuffle) buildShuffleQueue(currentIndex);
        });
    }

    // Audio element event listeners
    audio.addEventListener('timeupdate', () => {
        if (!audio.duration || isNaN(audio.duration)) return;
        const pct = (audio.currentTime / audio.duration) * 100;
        if (progressFill) progressFill.style.width = `${pct}%`;
        if (currentTimeEl) currentTimeEl.textContent = formatTime(audio.currentTime);
    });

    audio.addEventListener('loadedmetadata', () => {
        if (durationEl) durationEl.textContent = formatTime(audio.duration);
    });

    audio.addEventListener('ended', () => {
        nextTrack();
    });

    // Seeking
    if (progressWrap) {
        progressWrap.addEventListener('click', (e) => {
            if (!audio.duration || isNaN(audio.duration)) return;
            const rect = progressWrap.getBoundingClientRect();
            const clickPos = Math.max(0, Math.min(1, (e.clientX - rect.left) / rect.width));
            audio.currentTime = clickPos * audio.duration;
        });
    }

    // Volume Slider
    if (volumeSlider) {
        audio.volume = parseFloat(volumeSlider.value) || 0.85;
        volumeSlider.addEventListener('input', (e) => {
            audio.volume = parseFloat(e.target.value);
        });
    }

    // Drawer Toggles
    if (drawerToggle && drawer) {
        drawerToggle.addEventListener('click', () => {
            drawer.classList.toggle('is-open');
        });
    }

    if (drawerClose && drawer) {
        drawerClose.addEventListener('click', () => {
            drawer.classList.remove('is-open');
        });
    }

    // Initial Random Track Selection on Page Load (Stopped state)
    const initialRandomIdx = Math.floor(Math.random() * playlist.length);
    buildShuffleQueue(initialRandomIdx);
    loadTrack(initialRandomIdx, false);
}

function escapeHtml(str) {
    if (!str) return '';
    return str.replace(/[&<>"']/g, m => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;'
    }[m]));
}

/* ── Page-Level Suno Request Concurrency & Anti-Collision Controller ── */
let isSunoConnecting = false;
const sunoPendingQueue = [];
let isShortcutScrolling = false;
let shortcutScrollTimer = null;

function requestSunoActivation(iframe, isPriority = false) {
    if (!iframe || iframe.src) return;
    if (isPriority) {
        const idx = sunoPendingQueue.indexOf(iframe);
        if (idx > -1) sunoPendingQueue.splice(idx, 1);
        sunoPendingQueue.unshift(iframe);
    } else {
        if (!sunoPendingQueue.includes(iframe)) {
            sunoPendingQueue.push(iframe);
        }
    }
    processNextSunoRequest();
}

function processNextSunoRequest() {
    if (isSunoConnecting || sunoPendingQueue.length === 0) return;

    const frame = sunoPendingQueue.shift();
    if (!frame || frame.src) {
        processNextSunoRequest();
        return;
    }

    isSunoConnecting = true;
    frame.src = frame.dataset.src;

    let cleared = false;
    const releaseLock = () => {
        if (cleared) return;
        cleared = true;
        frame.removeEventListener('load', releaseLock);
        frame.removeEventListener('error', releaseLock);
        setTimeout(() => {
            isSunoConnecting = false;
            processNextSunoRequest();
        }, 600);
    };

    frame.addEventListener('load', releaseLock);
    frame.addEventListener('error', releaseLock);
    setTimeout(releaseLock, 3500);
}

function activateMostVisibleArtist() {
    if (isShortcutScrolling) return;
    const blocks = document.querySelectorAll('.artist-block');
    let bestBlock = null;
    let maxVisible = 0;
    const vh = window.innerHeight;

    blocks.forEach(block => {
        const rect = block.getBoundingClientRect();
        const visible = Math.max(0, Math.min(rect.bottom, vh) - Math.max(rect.top, 0));
        if (visible > maxVisible) {
            maxVisible = visible;
            bestBlock = block;
        }
    });

    if (bestBlock && maxVisible > 100) {
        const frame = bestBlock.querySelector('.suno-embed-frame');
        if (frame && !frame.src) {
            requestSunoActivation(frame);
        }
    }
}

function setupSunoRequestController() {
    // Intercept artist shortcut chip clicks
    document.querySelectorAll('.artist-shortcut-chip').forEach(chip => {
        chip.addEventListener('click', () => {
            const href = chip.getAttribute('href');
            if (!href || !href.startsWith('#')) return;
            const targetId = href.slice(1);
            const targetBlock = document.getElementById(targetId);
            if (!targetBlock) return;

            // Stop all intermediate activations during scroll
            isShortcutScrolling = true;
            clearTimeout(shortcutScrollTimer);
            sunoPendingQueue.length = 0; // Clear intermediate queue

            shortcutScrollTimer = setTimeout(() => {
                isShortcutScrolling = false;
                const targetFrame = targetBlock.querySelector('.suno-embed-frame');
                if (targetFrame && !targetFrame.src) {
                    requestSunoActivation(targetFrame, true);
                }
            }, 650);
        });
    });

    // Debounce manual window scrolling so fast scrolls don't spam requests
    let scrollDebounce = null;
    window.addEventListener('scroll', () => {
        if (isShortcutScrolling) return;
        clearTimeout(scrollDebounce);
        scrollDebounce = setTimeout(() => {
            activateMostVisibleArtist();
        }, 300);
    }, { passive: true });

    // Initial activation for the artist at the top
    setTimeout(activateMostVisibleArtist, 350);
}

